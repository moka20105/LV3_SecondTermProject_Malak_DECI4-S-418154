print("Repositories with 'Machine' in their name:")
display(df_machine_name)

"""### Logical Operators

Now, let's use logical operators (`AND`, `OR`, `NOT`) to create more specific SQL conditions and analyze our repository data.

#### Query using `AND`: Repositories with more than 50,000 stars and language is 'Python'
"""

query_and_operator = "SELECT name, owner, language, stars FROM Repositories WHERE stars > 50000 AND language = 'Python' ORDER BY stars DESC"
df_and_operator = pd.read_sql_query(query_and_operator, conn)

print("Repositories with >50,000 stars AND language 'Python':")
display(df_and_operator)

