import sqlite3
import pandas as pd

conn = sqlite3.connect(':memory:')

df_repositories = pd.read_csv('github_projects.csv')

df_repositories['created_date'] = pd.to_datetime(df_repositories['created_date'])
df_repositories['updated_date'] = pd.to_datetime(df_repositories['updated_date'])

df_repositories['created_date'] = df_repositories['created_date'].dt.strftime('%Y-%m-%d %H:%M:%S')
df_repositories['updated_date'] = df_repositories['updated_date'].dt.strftime('%Y-%m-%d %H:%M:%S')

df_repositories.to_sql('Repositories', conn, if_exists='replace', index=False)

print("Dataset successfully imported into SQLite table 'Repositories'.")

query = "SELECT name, owner, language, stars, created_date FROM Repositories LIMIT 5"
df_from_sql = pd.read_sql_query(query, conn)

print("Verifying data loaded into 'Repositories' table:")
display(df_from_sql)

"""### Filtering and Searching Queries

Now, let's perform the required filtering and searching tasks on the `Repositories` table in our SQLite database.

#### Filter repositories with more than 10,000 stars
"""

query_high_stars = "SELECT name, owner, language, stars FROM Repositories WHERE stars > 10000 ORDER BY stars DESC"
df_high_stars = pd.read_sql_query(query_high_stars, conn)

print("Repositories with more than 10,000 stars:")
display(df_high_stars)

"""#### Find repositories whose names contain the word “Machine”"""

query_machine_name = "SELECT name, owner, language, stars FROM Repositories WHERE name LIKE '%Machine%' COLLATE NOCASE"
